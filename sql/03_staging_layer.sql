CREATE OR REPLACE TABLE STAGING.STG_COLLISIONS AS
SELECT
    COLLISION_INDEX,
    COLLISION_YEAR,
    TO_DATE(DATE, 'DD/MM/YYYY') AS COLLISION_DATE,
    TRY_TO_TIME(TIME) AS COLLISION_TIME,
    COLLISION_SEVERITY,
    NUMBER_OF_VEHICLES,
    NUMBER_OF_CASUALTIES,
    WEATHER_CONDITIONS,
    ROAD_SURFACE_CONDITIONS,
    SPEED_LIMIT
FROM RAW.COLLISIONS_RAW;
